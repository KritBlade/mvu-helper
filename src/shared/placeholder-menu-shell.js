// shared/placeholder-menu-shell.js — the STAND-IN menu shell: mvu-helper's own ~1KB notice, not a
// working menu, and deliberately not the builder's.
//
// WHAT A SHELL IS. A StatusMenu Pack renders because ONE enabled regex on the card matches the
// placeholder MVU appends to every reply and replaces it with the menu body — chrome, runtime and
// all. MVU Status Menu Builder is what produces a real one: it composes its own stylesheet with the
// project's theme and bakes in the runtime the layout needs. That artifact belongs to the builder.
//
// WHY THIS FILE REPLACED A VENDORED COPY OF IT (user, 2026-08-31). mvu-helper used to carry the
// builder's real 201KB shell, regenerated by a tool in the other repo and guarded by a byte-drift
// check. Two things were wrong with that. It made this repo hold a build artifact of a repo it does
// not own — the one property the artifact doctrine exists to protect, since mvu-helper is a dumb
// terminal that carries and installs and never composes. And the guard only caught drift when
// somebody ran it, so the copy could age silently between releases.
//
// A stand-in has neither problem: it is this repo's own text, derived from nothing, so there is no
// drift to guard and no tool to run. What it costs is that a blank pack renders a NOTICE instead of
// an empty menu — which is more signal, not less: the message names the next step in the chat, where
// the developer is already looking.
//
// THE NAME IS THE CONTRACT. `script_name: 'StatusMenu'` is what the builder's real export also uses,
// and regex lifecycle matches on that name (never on `id`, which is per-installation). So dropping a
// real StatusMenu.json into the workspace REPLACES this row rather than sitting beside it, and the
// one-claimant rule holds without anyone deleting anything by hand.
//
// PLAIN HTML, NO FENCE, NO DOCUMENT (plans/executed/statusmenu-containment.md M2). A fenced <html> document is
// what TavernHelper renders into an unsandboxed iframe, and the whole containment rule is that no row
// this extension writes may carry one. A notice needs no script and no document: SillyTavern renders
// this markup directly, DOMPurify keeps `style` attributes (classes get its `custom-` prefix, so the
// styling rides inline), and nothing is rendered by TavernHelper at all. It ships inside a
// rendered-region container so the notice announces its own boundary the way every user-facing region
// mvu-helper draws does.

import { wrapRenderedRegion } from './rendered-region.js';

