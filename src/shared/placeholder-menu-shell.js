    '<h3 style="margin:0 0 6px;font-size:1em;color:#00e5ff;letter-spacing:.02em;">No menu built yet</h3>',
    '<p style="margin:6px 0 0;">This pack ships a PLACEHOLDER shell, so the pipeline works end to end and the dev loop',
    'applies without error - but there is no menu to draw.</p>',
    '<p style="margin:6px 0 0;">Design the real one in <b>MVU Status Menu Builder</b>, export the StatusMenu Pack, and drop',
    'its <code style="color:#81d4fa;">regex/StatusMenu.json</code> over this one. It carries the same script name, so it',
    'replaces this notice rather than sitting beside it.</p>',
    '<p style="margin:6px 0 0;opacity:.75;font-size:.9em;">Seeing this on a card whose pack DOES ship a menu means two regexes claim the',
    'placeholder and this one is winning on list order - disable or delete it.</p>',
    '</div>',
